/**
 * Response headers applied to every route in production.
 *
 * The app loads nothing from other origins, so the policy is same-origin only.
 * `'unsafe-inline'` is required because the framework emits inline bootstrap
 * scripts, the theme bootstrap is inline, and React writes inline `style`
 * attributes for CSS custom properties. Tightening this to nonces would need
 * per-request rendering and is tracked as a hardening follow-up.
 */
export const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "manifest-src 'self'",
  "media-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

export const SECURITY_HEADERS: readonly Readonly<{ key: string; value: string }>[] = Object.freeze([
  { key: "Content-Security-Policy", value: CONTENT_SECURITY_POLICY },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=(), usb=()" },
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
]);
